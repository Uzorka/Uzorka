export function productById(id: string): Product | undefined {
  return PRODUCTS.find((p) => p.id === id);
}
export function productBySlug(slug: string): Product | undefined {
  return PRODUCTS.find((p) => p.slug === slug);
}

/** Copy for the availability pill. Keeps one wording across the whole app. */
export function availabilityLabel(p: Product): {
  tone: "ok" | "warn" | "info" | "bad";
  text: string;
} {
  if (p.availability === "out") return { tone: "bad", text: "Sold out today" };
  if (p.availability === "preorder")
    return { tone: "info", text: "Pre-order — next landing" };
  if (p.availability === "limited")
    return { tone: "warn", text: `Only ${p.stockKg} kg left` };
  return { tone: "ok", text: p.landedHoursAgo <= 8 ? "Landed today" : "In stock" };
}

/** The searchable haystack for a product. */
export function searchTerms(p: Product): string {
  const cat = categoryOf(p.category);
  return [p.name, p.tagline, cat?.name, cat?.short, p.origin, ...(p.badges ?? [])]
    .join(" ")
    .toLowerCase();
}
